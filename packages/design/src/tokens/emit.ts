/**
 * The generators: the registry, rendered for each consumer (D232, D233).
 *
 * - `emitCss` — custom properties for the web, colors in `oklch()`, one block per surface × mode.
 * - `emitTailwind` — Tailwind v4 `@theme` wiring so utilities read those properties.
 * - `emitNative` — a TS module for React Native: colors as hex / `rgba()` (it parses no
 *   `oklch()`), lengths as dp numbers.
 * - `emitJson` — every token resolved in every map, for a script (the Paper push) to walk.
 *
 * All four are pure and deterministic: the same registry gives byte-identical output. Each one
 * validates first and refuses a length in the wrong unit class (`UnitClassError`).
 */

import { allThemeMaps, DEFAULT_MODE, DEFAULT_SURFACE, type ThemeMap, themeMaps } from './maps';
import { toCssOklch, toNativeColor } from './oklch';
import { registry, type ShadowLayer, type TokenEntry, type TokenValue } from './registry';
import {
  formatNumber,
  GROUP_UNIT,
  type Length,
  type LengthGroup,
  toCssLength,
  toNativeNumber,
  UnitClassError,
} from './units';

/** The unit-class group each registry group's lengths belong to (D233). */
const LENGTH_GROUP: Record<string, LengthGroup> = {
  'font-size': 'fontSize',
  size: 'size',
  gap: 'space',
  space: 'space',
  'letter-spacing': 'tracking',
  'line-height': 'leading',
  radius: 'radius',
  'border-width': 'border',
  breakpoint: 'breakpoint',
};

function expectUnit(name: string, length: Length, group: LengthGroup): void {
  const expected = GROUP_UNIT[group];
  if (length.unit !== expected) {
    throw new UnitClassError(
      `${name} is ${length.value}${length.unit}, but ${group} must be ${expected}`,
    );
  }
}

/**
 * Refuse any length in the wrong unit class, in every map. `space.px` is the one optical nudge in
 * the space group, and shadows are drawing, so both must be px.
 */
export function validateRegistry(entries: readonly TokenEntry[] = registry): void {
  for (const entry of entries) {
    for (const map of allThemeMaps) {
      const value = entry.value(map);
      if (value.kind === 'length') {
        const group =
          entry.group === 'space' && entry.key === 'px' ? 'nudge' : LENGTH_GROUP[entry.group];
        if (!group) throw new UnitClassError(`${entry.name} is a length in no unit class`);
        expectUnit(entry.name, value.length, group);
      } else if (value.kind === 'shadow') {
        for (const layer of value.layers) {
          for (const part of [layer.x, layer.y, layer.blur, layer.spread]) {
            if (part.unit !== 'px') {
              throw new UnitClassError(`${entry.name} has a ${part.unit} shadow; shadows are px`);
            }
          }
        }
      }
    }
  }
}

const GENERATED_NOTE =
  'Generated by @skating/design from its token source. Do not edit; run `pnpm --filter @skating/design generate`.';

// ── CSS ───────────────────────────────────────────────────────────────────────────────────────

function cssFamily(families: readonly string[]): string {
  return families.map((f) => (/\s/.test(f) ? `"${f}"` : f)).join(', ');
}

function cssShadow(layers: readonly ShadowLayer[]): string {
  return layers
    .map((l) => {
      const parts = [l.x, l.y, l.blur, l.spread].map(toCssLength).join(' ');
      return `${l.inset ? 'inset ' : ''}${parts} var(--${l.color})`;
    })
    .join(', ');
}

/** A token's value as CSS. */
export function cssValue(value: TokenValue): string {
  switch (value.kind) {
    case 'color':
      return toCssOklch(value.color);
    case 'length':
      return toCssLength(value.length);
    case 'number':
      return formatNumber(value.number);
    case 'fontFamily':
      return cssFamily(value.families);
    case 'shadow':
      return cssShadow(value.layers);
    case 'duration':
      return `${value.ms}ms`;
    case 'easing':
      return `cubic-bezier(${value.bezier.map(formatNumber).join(', ')})`;
  }
}

function block(selector: string, lines: readonly string[], indent = ''): string {
  return [`${indent}${selector} {`, ...lines.map((l) => `${indent}  ${l}`), `${indent}}`].join(
    '\n',
  );
}

function declarations(
  entries: readonly TokenEntry[],
  map: ThemeMap,
  include: (e: TokenEntry) => boolean,
): string[] {
  return entries.filter(include).map((e) => `${e.cssVar}: ${cssValue(e.value(map))};`);
}

/**
 * The web's custom properties. Resolution, by specificity:
 *
 * 1. `:root` — everything: the shared tokens plus the default map (`DEFAULT_SURFACE`,
 *    `DEFAULT_MODE`), which the color-scheme media query swaps when the page states no mode.
 * 2. `:root[data-surface="admin"]` — a surface stated without a mode gets its density.
 * 3. `:root:not([data-mode])` under `prefers-color-scheme` — the OS's choice when the page states
 *    no mode.
 * 4. `:root[data-mode=…]` — a mode stated without a surface.
 * 5. `:root[data-surface=…][data-mode=…]` — the four maps, complete.
 *
 * Only a block that *states* a mode sets `color-scheme` (native scrollbars and form controls), so a
 * page that themes itself some other way isn't overridden. Under `prefers-reduced-motion: reduce`
 * every duration is 0ms.
 */
export function emitCss(entries: readonly TokenEntry[] = registry): string {
  validateRegistry(entries);
  const defaultMap = themeMaps[DEFAULT_SURFACE][DEFAULT_MODE];
  const varying = (e: TokenEntry) => e.varies !== 'none';
  const byMode = (e: TokenEntry) => e.varies === 'mode';
  const bySurface = (e: TokenEntry) => e.varies === 'surface';
  const scheme = (map: ThemeMap) => `color-scheme: ${map.mode};`;

  const out: string[] = [`/* ${GENERATED_NOTE} */`, ''];
  out.push(
    block(
      ':root',
      declarations(entries, defaultMap, () => true),
    ),
  );
  for (const surface of Object.keys(themeMaps) as (keyof typeof themeMaps)[]) {
    if (surface === DEFAULT_SURFACE) continue;
    out.push(
      '',
      block(
        `:root[data-surface="${surface}"]`,
        declarations(entries, themeMaps[surface].light, bySurface),
      ),
    );
  }
  const osMode = DEFAULT_MODE === 'light' ? 'dark' : 'light';
  const osMap = themeMaps[DEFAULT_SURFACE][osMode];
  out.push(
    '',
    `@media (prefers-color-scheme: ${osMode}) {`,
    block(':root:not([data-mode])', declarations(entries, osMap, byMode), '  '),
    '}',
  );
  for (const mode of ['dark', 'light'] as const) {
    const map = themeMaps[DEFAULT_SURFACE][mode];
    out.push(
      '',
      block(`:root[data-mode="${mode}"]`, [scheme(map), ...declarations(entries, map, byMode)]),
    );
  }
  for (const map of allThemeMaps) {
    out.push(
      '',
      block(`:root[data-surface="${map.surface}"][data-mode="${map.mode}"]`, [
        scheme(map),
        ...declarations(entries, map, varying),
      ]),
    );
  }
  const durations = entries.filter((e) => e.group === 'duration');
  out.push(
    '',
    '@media (prefers-reduced-motion: reduce) {',
    block(
      ':root',
      durations.map((e) => `${e.cssVar}: 0ms;`),
      '  ',
    ),
    '}',
    '',
  );
  return out.join('\n');
}

// ── Tailwind ──────────────────────────────────────────────────────────────────────────────────

/**
 * Tailwind v4 wiring. Tokens that vary go in `@theme inline` as `var()` references, so a utility
 * reads whichever map the root states (`bg-panel`, `text-fg3`, `text-row`, `h-btn`, `p-gutter`).
 * Breakpoints go in a plain `@theme` as literals, because a media query can't read a custom
 * property. Shared values are referenced too, so the raw properties stay the one source.
 */
export function emitTailwind(entries: readonly TokenEntry[] = registry): string {
  validateRegistry(entries);
  const wired = entries.filter((e) => e.tailwindVar !== undefined);
  const literal = wired.filter((e) => e.group === 'breakpoint');
  const referenced = wired.filter((e) => e.group !== 'breakpoint');
  const anyMap = allThemeMaps[0] as ThemeMap;
  return [
    `/* ${GENERATED_NOTE} */`,
    '',
    block(
      '@theme inline',
      referenced.map((e) => `${e.tailwindVar}: var(${e.cssVar});`),
    ),
    '',
    block(
      '@theme',
      literal.map((e) => `${e.tailwindVar}: ${cssValue(e.value(anyMap))};`),
    ),
    '',
  ].join('\n');
}

// ── React Native ──────────────────────────────────────────────────────────────────────────────

/** A token's value for React Native: hex / `rgba()` colors, dp numbers, plain data otherwise. */
export function nativeValue(value: TokenValue, map: ThemeMap): unknown {
  switch (value.kind) {
    case 'color':
      return toNativeColor(value.color);
    case 'length':
      return toNativeNumber(value.length);
    case 'number':
      return value.number;
    case 'fontFamily':
      return value.families;
    case 'shadow':
      // React Native's `boxShadow` takes the CSS syntax, with colors it can parse.
      return value.layers
        .map((l) => {
          const parts = [l.x, l.y, l.blur, l.spread].map((p) => `${toNativeNumber(p)}px`).join(' ');
          return `${l.inset ? 'inset ' : ''}${parts} ${toNativeColor(map.colors[l.color])}`;
        })
        .join(', ');
    case 'duration':
      return value.ms;
    case 'easing':
      return value.bezier;
  }
}

/** Serialize plain data as a TS literal (single quotes, trailing commas, sorted by nothing). */
function tsLiteral(value: unknown, indent: string): string {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  if (typeof value === 'number' || typeof value === 'boolean') return String(value);
  if (Array.isArray(value)) {
    const inner = value.map((v) => tsLiteral(v, indent));
    return `[${inner.join(', ')}]`;
  }
  const next = `${indent}  `;
  const lines = Object.entries(value as Record<string, unknown>).map(
    ([k, v]) => `${next}${/^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`}: ${tsLiteral(v, next)},`,
  );
  return `{\n${lines.join('\n')}\n${indent}}`;
}

/** `font-size` → `fontSize`: group names read as properties in TS. */
export function camelCase(name: string): string {
  return name.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase());
}

function groupValues(
  entries: readonly TokenEntry[],
  map: ThemeMap,
  include: (e: TokenEntry) => boolean,
): Record<string, Record<string, unknown>> {
  const groups: Record<string, Record<string, unknown>> = {};
  for (const e of entries.filter(include)) {
    const group = camelCase(e.group);
    groups[group] ??= {};
    (groups[group] as Record<string, unknown>)[e.key] = nativeValue(e.value(map), map);
  }
  return groups;
}

/**
 * The mobile module: `nativeThemes[surface][mode]` holds everything that varies (colors, shadows —
 * their colors follow the mode — and density), `nativeTokens` everything shared. Lengths are dp
 * (rem × 16); letter-spacing (em) and line-height (ratio) stay multipliers of the font size.
 */
export function emitNative(entries: readonly TokenEntry[] = registry): string {
  validateRegistry(entries);
  const perMap = (e: TokenEntry) => e.varies !== 'none' || e.group === 'shadow';
  const themes: Record<string, Record<string, unknown>> = {};
  for (const map of allThemeMaps) {
    themes[map.surface] ??= {};
    (themes[map.surface] as Record<string, unknown>)[map.mode] = groupValues(entries, map, perMap);
  }
  const sharedTokens = groupValues(entries, allThemeMaps[0] as ThemeMap, (e) => !perMap(e));
  return [
    `// ${GENERATED_NOTE}`,
    '//',
    '// Colors are hex or rgba() because React Native parses no OKLCH. Lengths are dp numbers;',
    '// letter-spacing and line-height are multipliers of the font size being set.',
    '',
    `export const nativeThemes = ${tsLiteral(themes, '')} as const;`,
    '',
    `export const nativeTokens = ${tsLiteral(sharedTokens, '')} as const;`,
    '',
    'export type NativeSurface = keyof typeof nativeThemes;',
    "export type NativeMode = keyof (typeof nativeThemes)['admin'];",
    '',
  ].join('\n');
}

// ── JSON ──────────────────────────────────────────────────────────────────────────────────────

/**
 * Every token resolved in every map, for a script to walk (the Paper push). Each value carries the
 * CSS form and, for colors, the hex form too, so a target that can't take `oklch()` still can.
 */
export function emitJson(entries: readonly TokenEntry[] = registry): string {
  validateRegistry(entries);
  const maps: Record<string, Record<string, unknown>> = {};
  for (const map of allThemeMaps) {
    const resolved: Record<string, unknown> = {};
    for (const e of entries) {
      const value = e.value(map);
      resolved[e.name] = {
        css: cssValue(value),
        ...(value.kind === 'color' ? { native: toNativeColor(value.color) } : {}),
      };
    }
    maps[`${map.surface}/${map.mode}`] = resolved;
  }
  const tokens = entries.map((e) => ({
    name: e.name,
    varies: e.varies,
    cssVar: e.cssVar,
    ...(e.tailwindVar === undefined ? {} : { tailwindVar: e.tailwindVar }),
  }));
  return `${JSON.stringify({ $description: GENERATED_NOTE, tokens, maps }, null, 2)}\n`;
}

/** Every generated file, by its path under the package's `_generated/` directory. */
export function generateAll(entries: readonly TokenEntry[] = registry): Record<string, string> {
  return {
    'tokens.css': emitCss(entries),
    'tailwind.css': emitTailwind(entries),
    'native.ts': emitNative(entries),
    'tokens.json': emitJson(entries),
  };
}
