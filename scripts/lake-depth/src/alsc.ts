/**
 * Flatten the report to **one field per line**, decoding the entities this site actually emits.
 *
 * The line break is the whole trick. Every value is a `<li>Label: value</li>`, and once the markup
 * is gone the only thing separating `Max Depth (m): 1.2` from the next field is the item boundary —
 * so a parser that flattens to a single string has to guess where a value ends, and guesses wrong
 * the moment a value contains a colon (every coordinate does: `43°46'08" N` does not, but
 * `Volume(m3)` and `WA/SA ratio` sit next to fields that do). Turning `</li>` into a newline first
 * makes each field self-delimiting and the rest of this file boring.
 */
export function textOf(html: string): string {
  return html
    .replace(/<sup>[^<]*<\/sup>/gi, '')
    .replace(/<\s*(?:\/li|br\s*\/?|\/tr|\/p|\/h[1-6]|\/div)\s*>/gi, '\n')
    .replace(/<[^>]*>/g, ' ')
    .replace(/&deg;/gi, '°')
    .replace(/&quot;/gi, '"')
    .replace(/&nbsp;/gi, ' ')
    .replace(/&amp;/gi, '&')
    .replace(/&gt;/gi, '>')
    .replace(/&lt;/gi, '<')
    .replace(/&#39;|&apos;/gi, "'")
    .replace(/[^\S\n]+/g, ' ')
    .replace(/ ?\n ?/g, '\n')
    .replace(/\n{2,}/g, '\n')
    .trim();
}

/**
 * `43°46'08" N` → 43.768…, and `074°31'42" W` → **negative**.
 *
 * The hemisphere letter is the only thing carrying the sign — the degrees are published unsigned and
 * zero-padded — so a parser that ignores it puts every Adirondack pond in Kazakhstan. Returns
 * `undefined` rather than a partial reading: a coordinate is the join key, and a wrong one attaches
 * a real depth to the wrong lake, which is worse than attaching none.
 */
export function parseDms(text: string): number | undefined {
  const m = /(\d+)\s*°\s*(\d+)\s*'\s*(\d+(?:\.\d+)?)\s*"?\s*([NSEW])/i.exec(text);
  if (!m) return undefined;
  const [, d, min, sec, hemi] = m;
  const value = Number(d) + Number(min) / 60 + Number(sec) / 3600;
  if (!Number.isFinite(value)) return undefined;
  return /[SW]/i.test(hemi ?? '') ? -value : value;
}

/**
 * The value of a `Label: value` list item, or `undefined` when the field is present but blank.
 *
 * Matches **within one line** — see `textOf`. A blank field is a real and common state (the survey
 * did not measure everything at every pond) and must read as absent rather than as an empty string,
 * which would otherwise reach `Number('')` and become a very confident `0`.
 */
export function fieldValue(text: string, label: string): string | undefined {
  // Labels carry units and punctuation the caller should not have to escape by hand.
  const escaped = label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const m = new RegExp(`^\\s*${escaped}\\s*:\\s*(.*)$`, 'im').exec(text);
  const value = m?.[1]?.trim();
  return value === undefined || value.length === 0 ? undefined : value;
}

function numberField(text: string, label: string): number | undefined {
  const raw = fieldValue(text, label);
  if (raw === undefined) return undefined;
  const m = /-?\d+(?:\.\d+)?/.exec(raw);
  if (!m) return undefined;
  const n = Number(m[0]);
  return Number.isFinite(n) ? n : undefined;
}

/**
 * Deepest reading we will accept, in metres.
 *
 * **Lake Champlain's 122 m is the deepest water in the region and is not in the Adirondack Park.**
 * The deepest Adirondack lake, Lake George, is ~59 m. 200 m is generous by more than three times
 * against the survey's own subject matter, which is the right direction for a backstop: it exists to
 * catch a units error or a mis-parsed field, not to adjudicate a real sounding.
 */
export const MAX_PLAUSIBLE_ALSC_DEPTH_M = 200;

/** Why a fetched report yielded no usable record. Counted apart — they mean different things. */
export type AlscRefusal =
  /** The response was not a pond report — an error page, or a pond number the site does not know. */
  | 'not-a-report'
  /** A report with no depth at all. Real: the survey did not sound every pond it visited. */
  | 'no-depth'
  /** A depth outside the plausible window, i.e. a parse or units failure rather than a lake. */
  | 'implausible';

export type AlscOutcome =
  | { readonly ok: true; readonly pond: AlscPond }
  | { readonly ok: false; readonly reason: AlscRefusal };

/**
 * One pond report → a record, or a counted refusal.
 *
 * Reads the flattened text rather than the DOM, because the page's structure is a nested `<ul>` of
 * `<li style="list-style-type:none">Label: value</li>` and the labels are stable where the markup is
 * not — this is a 2005-era template that has already survived one redesign.
 */
export function parseAlscReport(html: string, expectedPond?: string): AlscOutcome {
  const text = textOf(html);
  const name = fieldValue(text, 'Pond Name');
  const pondNumber = fieldValue(text, 'Pond #');
  if (name === undefined || pondNumber === undefined) return { ok: false, reason: 'not-a-report' };
  // The report echoes the pond number it actually served. A mismatch means the site resolved our
  // query to something else, and silently keying that under the number we asked for is how a depth
  // lands on the wrong lake.
  if (expectedPond !== undefined && pondNumber !== expectedPond) {
    return { ok: false, reason: 'not-a-report' };
  }

  const maxDepthM = numberField(text, 'Max Depth (m)');
  const meanDepthM = numberField(text, 'Mean Depth (m)');
  if (maxDepthM === undefined && meanDepthM === undefined) return { ok: false, reason: 'no-depth' };
  for (const d of [maxDepthM, meanDepthM]) {
    if (d !== undefined && (d <= 0 || d > MAX_PLAUSIBLE_ALSC_DEPTH_M)) {
      return { ok: false, reason: 'implausible' };
    }
  }
  // A mean deeper than the max is arithmetically impossible and means the two fields were read
  // across each other — the exact failure a label-based parser has, and one that looks plausible.
  if (maxDepthM !== undefined && meanDepthM !== undefined && meanDepthM > maxDepthM) {
    return { ok: false, reason: 'implausible' };
  }

  const elevationRaw = numberField(text, 'Elevation (m)');
  return {
    ok: true,
    pond: {
      pondNumber,
      name,
      county: fieldValue(text, 'County'),
      town: fieldValue(text, 'Town'),
      lat: parseDms(fieldValue(text, 'Latitude (DD°MM\'SS")') ?? ''),
      lng: parseDms(fieldValue(text, 'Longitude (DD°MM\'SS")') ?? ''),
      elevationM: isPlausibleElevationM(elevationRaw) ? elevationRaw : undefined,
      surfaceAreaHa: numberField(text, 'Surface Area (ha)'),
      maxDepthM,
      meanDepthM,
      shorelineKm: numberField(text, 'Shoreline Length (km)'),
      // `Volume(m<sup>3</sup>)` — the superscript is stripped, so the label reads `Volume(m)`.
      volumeM3: numberField(text, 'Volume(m)'),
    },
  };
}

/** A pond the county listing named, before its report has been fetched. */
export interface AlscPondRef {
  pondNumber: string;
  name: string;
}

/**
 * Pull `alscpond` / `pname` pairs out of a county listing.
 *
 * Deduped on the pond number, because a pond on a county line is listed by both of them — and the
 * whole point of enumerating by county is that twelve requests replace fifteen hundred.
 */
export function parsePondList(html: string): AlscPondRef[] {
  const out = new Map<string, AlscPondRef>();
  const re = /alscrpt\.inc\.php\?alscpond=([0-9]+)&(?:amp;)?pname=([^"'>]+)/gi;
  for (const m of html.matchAll(re)) {
    const pondNumber = m[1];
    const name = decodeURIComponent((m[2] ?? '').replace(/\+/g, ' ')).trim();
    if (!pondNumber || name.length === 0) continue;
    if (!out.has(pondNumber)) out.set(pondNumber, { pondNumber, name });
  }
  return [...out.values()];
}

/**
 * Does the scraped set agree with data we already hold? — **the answer to the bad certificate.**
 *
 * A certificate proves you are talking to the right server; it says nothing about whether the bytes
 * mean what you think. Since we could not have the first, take the second and take it properly: if
 * ALSC's surface areas agree with polygons we drew from OSM and NHD, and its names agree with the
 * federal gazetteer, then the payload is the survey it claims to be — from three publishers that
 * have never met.
 *
 * Returns the share of matched ponds whose area agrees within `toleranceRatio`. Deliberately a
 * *fraction of the comparable set*, not of everything: a pond our corpus has no counterpart for is
 * not evidence either way, and folding it in as agreement is the misleading-denominator shape the
 * depth join's coverage block was rebuilt to avoid.
 */
export function corroborate(
  ponds: readonly AlscPond[],
  known: ReadonlyMap<string, { areaSqM: number }>,
  toleranceRatio = 0.35,
): { comparable: number; agreeing: number; rate: number } {
  const SQ_M_PER_HA = 10_000;
  let comparable = 0;
  let agreeing = 0;
  for (const pond of ponds) {
    if (pond.surfaceAreaHa === undefined || pond.surfaceAreaHa <= 0) continue;
    const match = known.get(pond.pondNumber);
    if (match === undefined || match.areaSqM <= 0) continue;
    comparable++;
    const ours = match.areaSqM;
    const theirs = pond.surfaceAreaHa * SQ_M_PER_HA;
    const ratio = Math.min(ours, theirs) / Math.max(ours, theirs);
    if (ratio >= 1 - toleranceRatio) agreeing++;
  }
  return { comparable, agreeing, rate: comparable > 0 ? agreeing / comparable : 0 };
}
