/**
 * The **Adirondack Lakes Survey** (1984–87) — New York's only large measured-depth source (N7-2).
 *
 * ## Why this exists, and why it is a scraper
 *
 * New York is 9,422 bodies of the corpus and has had effectively no measured depth: the statewide
 * bathymetry search came back empty twice (`scripts/bathymetry/src/sources.ts`'s `NEW_YORK_STATUS`,
 * re-confirmed against the ArcGIS Hub catalogue 2026-08-08), and NYSDEC's CSLAP layer carries 278
 * lakes. The ALSC surveyed **1,469 Adirondack lakes** — 52% of the ponded waters in the region — and
 * publishes, per pond: max depth, mean depth, elevation, surface area, watershed area, littoral
 * area, shoreline length, volume and coordinates.
 *
 * **There is no bulk download.** The `.zip` files the site offers are water chemistry and long-term
 * monitoring; the 1984–87 morphometry is reachable only through a per-pond PHP report. So this is a
 * scraper, and that is a deliberate exception rather than a pattern to copy.
 *
 * ## The three things that were checked before writing it (2026-08-08)
 *
 * 1. **The TLS certificate does not validate.** It is a Let's Encrypt certificate for
 *    `www.server266.com` — a shared host that never issued one for this domain. Benign, and
 *    recorded rather than hidden: the manifest says the transport was unverified, and the payload is
 *    corroborated against data we already hold (see `corroborate`). A cross-check that agrees with
 *    GNIS names and our own polygon areas is better evidence than a certificate anyway.
 * 2. **`robots.txt` is a blanket `Disallow: /`.** Founder call, 2026-08-08: treat it as aimed at
 *    search indexers, on the ALSC's own published mission — *"for the benefit of regulatory agencies
 *    and the general public… through an exchange of objective information."* Recorded here because
 *    the next person deserves to find the reasoning, not just the code.
 * 3. **There is no licence.** Not "we did not look": every page was checked and the site publishes
 *    no terms-of-use, no data-use statement and no rights page — only a footer `copyright ©` whose
 *    year is generated by JavaScript from the current date, i.e. template boilerplate. So the honest
 *    record is *"no published terms"*, and the response to that is **attribution**, which
 *    `DEPTH_SOURCE_TERMS` carries.
 *
 * ## What the archived set actually is, measured (2026-08-08)
 *
 * **1,345 ponds, every one carrying both a max and a mean depth, zero refusals.** Internally
 * consistent — no mean deeper than its max, every coordinate inside the Adirondack box, elevations
 * 137–1,129 m. And it corroborates itself: the parsed maximum surface area is **287 ha = 709
 * acres**, against the ALSC's own prose describing a survey of lakes *"ranging in size from about
 * 0.5 to 700 acres"*. The data matches the published description of itself.
 *
 * ⚠ **That size ceiling is the honest limit of this source.** It is a survey of *small* ponds:
 * median 6 ha. Lake George, Schroon and Indian Lake are not in it, so the largest Adirondack water
 * — the water most people skate — still has no measured depth from here.
 *
 * ## Join on the NAME, never on the coordinate — measured, not assumed
 *
 * The published coordinates are DMS to the second and are **imprecise rather than merely offset**.
 * Against name-matched corpus bodies the offset has a small systematic component (~72 m north,
 * ~97 m east, about the size of a NAD27→WGS84 shift for New York) and a much larger random one
 * (**sd ~340 m**, median error 289 m). A pond of the median size is ~275 m across, so a datum
 * correction would recover a third of the error and leave the rest.
 *
 * The consequence is concrete: point-in-polygon matches **326** of 1,345, and a name match within
 * 2 km matches **866**.
 *
 * **What actually ships is the shared join, not a wider one for this source.** `transform.ts` emits
 * ALSC as ordinary `DepthRecord`s and `matchAndImportDepths` matches them the way it matches every
 * other source: containment first, then proximity inside `DEPTH_PROXIMITY_METERS` (500 m) with the
 * name or the area corroborating. So the ceiling here is 500 m, not the 2 km the measurement above
 * describes, and the difference is deliberate — the source with the *worst* coordinates is the last
 * one that should be handed a looser rule, and the load names every pond it declined.
 *
 * The 2 km name join remains the upgrade worth making, and it wants two things this one does not
 * have: a distance bound passed per source rather than per deployment, and `nameClaims` rather than
 * the stored name, because N7 keeps every publisher's name and ALSC's spelling may agree with OSM's
 * where the stored one is NHD's. Until then the shortfall is visible in the run row instead of
 * assumed away.
 *
 * The pure half is here and tested; the fetching, pacing and archiving is `snapshotAlsc.ts`, and
 * the read-back into the depth pipeline is `parseAlscArchive` in `transform.ts`.
 */

